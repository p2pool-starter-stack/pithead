#!/usr/bin/env bash
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$HERE/../lib.sh"
INTEGRATION_RUN_SUITE=1 source "$HERE/../lib/run-uninstall.sh"

rx() { bash -c "$1"; }
docker() {
    [ "${INVENTORY_CASE:-}" != docker-fails ] || return 1
    case "$*" in
    'container ls -aq --no-trunc')
        [ "${INVENTORY_CASE:-}" != reordered-containers ] || printf 'second-container\n'
        printf '%s\n' "${CONTAINER_ID:-container}"
        [ "${INVENTORY_CASE:-}" = reordered-containers ] || printf 'second-container\n'
        ;;
    'image ls -q --no-trunc')
        if [ "${INVENTORY_CASE:-}" = reordered ]; then printf 'image-b\n%s\n' "${IMAGE_ID:-image-a}"; else printf '%s\nimage-b\n' "${IMAGE_ID:-image-a}"; fi
        ;;
    'volume ls -q')
        [ "${INVENTORY_CASE:-}" != reordered-volumes ] || printf 'second-volume\n'
        printf '%s\n' "${VOLUME_ID:-volume}"
        [ "${INVENTORY_CASE:-}" = reordered-volumes ] || printf 'second-volume\n'
        ;;
    'compose stop')
        printf 'stop\n' >>"$QUIESCE_TRACE"
        [ "${INVENTORY_CASE:-}" != stop-fails ]
        ;;
    *) return 90 ;;
    esac
}
systemctl() {
    [ "${INVENTORY_CASE:-}" != systemd-fails ] || return 1
    case "$*" in
    'list-unit-files --no-legend')
        [ "${INVENTORY_CASE:-}" != reordered-systemd ] || printf 'pithead-egress.timer enabled\n'
        printf 'pithead-control.service%s%s\n' "${UNIT_GAP:- }" "${UNIT_STATE:-enabled}"
        [ "${INVENTORY_CASE:-}" = reordered-systemd ] || printf 'pithead-egress.timer enabled\n'
        ;;
    'list-units --all --no-legend') printf 'pithead-control.service loaded active running control\n' ;;
    'is-active pithead-lan.timer')
        printf 'state\n' >>"$QUIESCE_TRACE"
        printf '%s\n' "${TIMER_STATE:-inactive}"
        ;;
    *) return 91 ;;
    esac
}
sudo() {
    if [ "$*" = '-n nft list tables' ]; then
        nft list tables
        return $?
    fi
    [ "$*" = '-n iptables-save' ] || return 92
    [ "${INVENTORY_CASE:-}" != firewall-fails ] || return 1
    printf '# Generated by iptables-save on %s\n*filter\n:INPUT ACCEPT [%s]\n' "${CAPTURE_TIME:-first}" "${COUNTERS:-0:0}"
    if [ "${INVENTORY_CASE:-}" = rule-order ]; then printf '%s\n' '-A INPUT -j DROP'; fi
    printf '%s\n' "-A INPUT -m comment --comment \"${RULE_COMMENT:-keep [3:4]}\" -j ${RULE_TARGET:-ACCEPT}"
    if [ "${INVENTORY_CASE:-}" != rule-order ]; then printf '%s\n' '-A INPUT -j DROP'; fi
    printf 'COMMIT\n# Completed on %s\n' "${CAPTURE_TIME:-first}"
}
nft() {
    [ "${INVENTORY_CASE:-}" != nft-fails ] || return 1
    [ "${INVENTORY_CASE:-}" != reordered-nft ] || printf 'table inet fixture\n'
    printf 'table inet %s\n' "${TABLE_NAME:-pithead_egress}"
    [ "${INVENTORY_CASE:-}" = reordered-nft ] || printf 'table inet fixture\n'
}
export -f docker systemctl sudo nft

echo "== uninstall compares resources rather than capture metadata =="
baseline="$(_uninstall_host_inventory)"
assert_rc 'the baseline inventory succeeds' "$?" 0
assert_eq 'capture timestamps and packet counters do not change resources' \
    "$(CAPTURE_TIME=second COUNTERS=12:345 _uninstall_host_inventory)" "$baseline"
assert_eq 'Docker listing order does not change image identities' "$(INVENTORY_CASE=reordered _uninstall_host_inventory)" "$baseline"
assert_eq 'Docker listing order does not change container identities' "$(INVENTORY_CASE=reordered-containers _uninstall_host_inventory)" "$baseline"
assert_eq 'Docker listing order does not change volume identities' "$(INVENTORY_CASE=reordered-volumes _uninstall_host_inventory)" "$baseline"
assert_eq 'systemd listing order does not change unit identities' "$(INVENTORY_CASE=reordered-systemd _uninstall_host_inventory)" "$baseline"
assert_eq 'systemd column padding does not change unit state' "$(UNIT_GAP='    ' _uninstall_host_inventory)" "$baseline"
assert_eq 'nft listing order does not change table identities' "$(INVENTORY_CASE=reordered-nft _uninstall_host_inventory)" "$baseline"
assert_ne 'a changed container identity is still detected' "$(CONTAINER_ID=other _uninstall_host_inventory)" "$baseline"
assert_ne 'a changed image identity is still detected' "$(IMAGE_ID=other _uninstall_host_inventory)" "$baseline"
assert_ne 'a changed volume identity is still detected' "$(VOLUME_ID=other _uninstall_host_inventory)" "$baseline"
assert_ne 'a changed nft table identity is still detected' "$(TABLE_NAME=other _uninstall_host_inventory)" "$baseline"
assert_ne 'a firewall target change is still detected' "$(RULE_TARGET=REJECT _uninstall_host_inventory)" "$baseline"
assert_ne 'firewall rule order is still significant' "$(INVENTORY_CASE=rule-order _uninstall_host_inventory)" "$baseline"
assert_ne 'counter-shaped text in a rule comment is preserved' "$(RULE_COMMENT='keep [8:9]' _uninstall_host_inventory)" "$baseline"
assert_ne 'a systemd unit state change is still detected' "$(UNIT_STATE=disabled _uninstall_host_inventory)" "$baseline"
for INVENTORY_CASE in docker-fails systemd-fails firewall-fails nft-fails; do
    export INVENTORY_CASE
    _uninstall_host_inventory >/dev/null 2>&1
    assert_ne "$INVENTORY_CASE cannot produce a passing inventory" "$?" 0
done
unset INVENTORY_CASE

echo "== uninstall quiesces the node recovery timer without removing resources =="
trace_dir="$(mktemp -d)"
trap 'rm -rf "$trace_dir"' EXIT
export QUIESCE_TRACE="$trace_dir/trace"
_lan_timer_pause() {
    printf 'pause\n' >>"$QUIESCE_TRACE"
    [ "${INVENTORY_CASE:-}" != pause-fails ]
}
_uninstall_quiesce
assert_rc 'an inactive timer permits stopping the containers' "$?" 0
assert_eq 'the timer is paused and verified before stopping containers' "$(cat "$QUIESCE_TRACE")" $'pause\nstate\nstop'
TIMER_STATE=failed _uninstall_quiesce
assert_rc 'a failed timer is also quiescent' "$?" 0
for INVENTORY_CASE in pause-fails stop-fails systemd-fails; do
    export INVENTORY_CASE
    _uninstall_quiesce >/dev/null 2>&1
    assert_ne "$INVENTORY_CASE refuses the preservation measurement" "$?" 0
done
unset INVENTORY_CASE
: >"$QUIESCE_TRACE"
TIMER_STATE=active _uninstall_quiesce >/dev/null 2>&1
assert_ne 'a timer that stayed active refuses the preservation measurement' "$?" 0
assert_eq 'an active timer prevents Compose stop from running' "$(cat "$QUIESCE_TRACE")" $'pause\nstate'

echo "selftest-uninstall-inventory: $IT_PASS passed, $IT_FAIL failed"
[ "$IT_FAIL" -eq 0 ]
